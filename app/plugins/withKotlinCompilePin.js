// Fixes the EAS Android build failing at ":expo:compileReleaseKotlin" with
//   "kotlin-stdlib-2.4.0.jar ... Module was compiled with an incompatible version of Kotlin. The binary version of
//    its metadata is 2.4.0, expected version is 2.1.0."
//
// Why: Expo SDK 54 compiles every module with Kotlin 2.1.20. LiteRT-LM (the Void AI runtime) was built with Kotlin 2.4
// and brings kotlin-stdlib / kotlin-reflect 2.4.0. app/modules/void-ai-runtime already pins those for ITS OWN classpath,
// but the `expo` module depends on every autolinked module, so 2.4.0 leaks onto the classpath of OTHER modules too.
//
// What this does: app/android is generated by `expo prebuild` on EAS, so the fix has to be a config plugin. It adds a
// block to the root android/build.gradle that, for every module:
//   1. pins kotlin-stdlib* / kotlin-reflect to the app's Kotlin version on COMPILE classpaths only (the app still gets
//      the newer libraries at run time, which is safe: a newer stdlib runs older code, and LiteRT-LM needs it);
//   2. lets the 2.1 compiler read newer Kotlin metadata (-Xskip-metadata-version-check), as the Void AI module does.
const { withProjectBuildGradle } = require("expo/config-plugins");

const MARK = "// voidpop:kotlin-compile-pin";

const BLOCK = `
${MARK}
allprojects { p ->
  p.configurations.configureEach { cfg ->
    if (cfg.name.toLowerCase().contains("compileclasspath")) {
      cfg.resolutionStrategy.eachDependency { details ->
        if (details.requested.group == "org.jetbrains.kotlin" &&
            (details.requested.name.startsWith("kotlin-stdlib") || details.requested.name == "kotlin-reflect")) {
          def appKotlin = rootProject.findProperty("kotlinVersion") ?: "2.1.20"
          details.useVersion(appKotlin.toString())
          details.because("LiteRT-LM brings Kotlin 2.4 libraries; modules are compiled by the app's Kotlin")
        }
      }
    }
  }
  p.tasks.configureEach { task ->
    if (task.name.startsWith("compile") && task.name.endsWith("Kotlin") && task.hasProperty("compilerOptions")) {
      task.compilerOptions.freeCompilerArgs.add("-Xskip-metadata-version-check")
    }
  }
}
`;

module.exports = function withKotlinCompilePin(config) {
  return withProjectBuildGradle(config, (c) => {
    if (c.modResults.language !== "groovy") {
      throw new Error("withKotlinCompilePin: the root build.gradle isn't Groovy; the Kotlin pin can't be added.");
    }
    if (!c.modResults.contents.includes(MARK)) c.modResults.contents += BLOCK; // once, even if prebuild runs twice
    return c;
  });
};
module.exports.BLOCK = BLOCK;
