// Builds src/lib/storyVideoHtml.js: the page the app's hidden WebView loads to
// turn Rewind story images into an MP4 (see src/components/StoryVideoMaker.js).
// It inlines the mp4-muxer library, shared/storyVideo.js and shared/storyMusic.js, since a WebView
// page can't import packages. Run after changing shared/storyVideo.js or
// updating mp4-muxer:   node app/scripts/story-video-html.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const require = createRequire(import.meta.url);
// the package's "require" entry is the plain-script build (it defines Mp4Muxer)
const muxer = readFileSync(require.resolve("mp4-muxer", { paths: [root] }), "utf8")
  .replace(/if \(typeof module === "object"[^\n]*\n?$/, "");
const encoder = readFileSync(join(root, "shared", "storyVideo.js"), "utf8").replace(/^export /gm, "");
const music = readFileSync(join(root, "shared", "storyMusic.js"), "utf8").replace(/^export /gm, "");

const page = `<!doctype html><html><head><meta charset="utf-8"></head><body><script>
${muxer}
${encoder}
${music}
(function () {
  var frames = [];
  function send(m) { window.ReactNativeWebView.postMessage(JSON.stringify(m)); }
  function toBase64(bytes) {
    var s = "", step = 0x8000;
    for (var i = 0; i < bytes.length; i += step) s += String.fromCharCode.apply(null, bytes.subarray(i, i + step));
    return btoa(s);
  }
  function load(src) {
    return new Promise(function (ok, fail) { var img = new Image(); img.onload = function () { ok(img); }; img.onerror = fail; img.src = src; });
  }
  async function onMessage(e) {
    var m; try { m = JSON.parse(e.data); } catch (x) { return; }
    if (m.type === "frame") { frames.push(m.data); return; }
    if (m.type !== "go") return;
    try {
      var images = [];
      for (var i = 0; i < frames.length; i++) images.push(await load("data:image/jpeg;base64," + frames[i]));
      var soundtrack = m.music ? await renderSoundtrack(images.length * 3).catch(function () { return null; }) : null;
      var out = await makeStoryVideo(Mp4Muxer, images, { width: m.width, height: m.height, music: soundtrack, onProgress: function (p) { send({ type: "progress", p: p }); } });
      var b64 = toBase64(out.bytes), size = 256 * 1024, n = Math.ceil(b64.length / size);
      for (var k = 0; k < n; k++) send({ type: "chunk", i: k, n: n, data: b64.slice(k * size, (k + 1) * size) });
      send({ type: "done", h264: out.h264, audio: out.audio });
    } catch (err) {
      send({ type: "error", message: String(err && err.message || err) });
    }
  }
  document.addEventListener("message", onMessage); // Android
  window.addEventListener("message", onMessage); // iOS
  send({ type: "ready", webcodecs: typeof VideoEncoder !== "undefined" });
})();
</script></body></html>`;

writeFileSync(join(root, "app", "src", "lib", "storyVideoHtml.js"),
  `// Generated by app/scripts/story-video-html.mjs. Don't edit by hand.\nexport const STORY_VIDEO_HTML = ${JSON.stringify(page)};\n`);
console.log(`storyVideoHtml.js: ${Math.round(page.length / 1024)} KB`);
